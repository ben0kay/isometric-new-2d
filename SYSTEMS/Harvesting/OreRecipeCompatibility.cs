    private static string Hash(string path)
    {
        if (!Godot.FileAccess.FileExists(path)) return "";
        string text = Encoding.UTF8.GetString(Godot.FileAccess.GetFileAsBytes(path))
            .TrimStart('\uFEFF').Replace("\r\n", "\n").Replace("\r", "\n").TrimEnd('\n') + "\n";
        return Convert.ToHexString(SHA256.HashData(Encoding.UTF8.GetBytes(text)));
    }
    public static bool Allows(string path, string savedHash) =>
        path == "res://WORLD/Contents/Ores/Iron/IronDeposit.tres" && Array.IndexOf(Before, savedHash) >= 0 &&
        Hash(path) == "0610CEC1EDBD1AFBCC2585F7C66400283C73DCC7CB49C60AA65B85599EF0AB80" &&
